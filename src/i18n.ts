export function translateText(text: string, locale: Locale): string {
  if (locale === "en") return text;
  const trimmed = text.trim();
  const exact = italian[trimmed];
  const start = text.indexOf(trimmed);
  if (exact !== undefined) return `${text.slice(0, start)}${exact}${text.slice(start + trimmed.length)}`;
  for (const [pattern, translate] of dynamicTranslations) {
    const match = trimmed.match(pattern);
    if (match) {
      return `${text.slice(0, start)}${translate(match)}${text.slice(start + trimmed.length)}`;
    }
  }
  return text;
}

export function formatLocale(locale: Locale): string {
  return locale === "it" ? "it-IT" : "en-US";
}
